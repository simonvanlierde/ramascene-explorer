"""Build the README's agreement table from results/*.json.

    uv run python table.py           # rewrite the table in README.md
    uv run python table.py --check   # exit 1 if README.md is out of date (CI)

The routes need the EXIOBASE arrays, so CI cannot rerun them; it checks that the
table matches the committed results. A new route adds its script and one row here.
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
START, END = "<!-- agreement-table: generated by table.py -->", "<!-- /agreement-table -->"

# label (formatted with the results file's fields), results file, key path to the score; the first row is the reference
ROUTES = [
    ("Brightway (bw2calc, SuperLU)", "lca.json", ["brightway"]),
    ("numpy, dense solve of I - A", "lca.json", ["numpy_solve_full_A"]),
    ("numpy, I - A with the same entries dropped as in Brightway", "lca.json", ["numpy_solve_cutoff_A"]),
    ("column of the shipped L matrix", "lca.json", ["numpy_L_file"]),
    ("RaMa-Scene engine, `route_one`", "engine.json", ["engine_result", "Cement, lime and plaster"]),
    ("pymrio {pymrio}, `calc_all` with its own inverse", "pymrio.json", ["score_D_cba"]),
]


def row(label, file, path):
    value = results = json.loads((HERE / "results" / file).read_text())
    for key in path:
        value = value[key]
    return label.format(**results), float(value)


def table():
    rows = [row(*route) for route in ROUTES]
    reference = rows[0][1]
    lines = ["| Route | Score (kg CO2 eq) | Relative difference |", "| --- | --- | --- |"]
    for i, (label, value) in enumerate(rows):
        diff = "reference" if i == 0 else f"{abs(value - reference) / abs(reference):.1e}"
        lines.append(f"| {label} | {value!r} | {diff} |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if README.md differs instead of writing it")
    args = ap.parse_args()
    readme = HERE / "README.md"
    text = readme.read_text()
    head, found_start, rest = text.partition(START)
    _, found_end, tail = rest.partition(END)
    if not (found_start and found_end):
        sys.exit(f"brightway-check/README.md: missing the {START} ... {END} markers around the table")
    new = f"{head}{START}\n{table()}\n{END}{tail}"
    if new == text:
        return
    if args.check:
        sys.exit("brightway-check/README.md: the agreement table is out of date; run table.py")
    readme.write_text(new)


if __name__ == "__main__":
    main()
